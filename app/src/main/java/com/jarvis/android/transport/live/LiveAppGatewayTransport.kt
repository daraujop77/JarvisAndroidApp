/**
 * Project-scoped Global Chat permits at most one read-only image OR document.
 * The VPS enforces <=3 MiB decoded image bytes, stricter than the global
 * three-image chat limit. Reject locally before starting the scoped request
 * rather than sending a payload the authoritative project route must refuse.
 * Base64 here is generated by chatPayload from app-private staged bytes.
 */
internal fun requireProjectAgentMediaWithinWireContract(
    images: kotlinx.serialization.json.JsonArray?,
    documents: kotlinx.serialization.json.JsonArray?,
) {
    val countImages = images?.size ?: 0
    val countDocuments = documents?.size ?: 0
    if (countImages > 1 || countDocuments > 1 ||
        (countImages > 0 && countDocuments > 0)
    ) throw TransportException("Project chat supports one image or one document per message")
    images?.forEach { item ->
        val encoded = runCatching {
            item.jsonObject["data_base64"]?.jsonPrimitive?.content.orEmpty()
        }.getOrElse { "" }
        val padding = encoded.takeLast(2).count { it == '=' }
        val decodedSize = (encoded.length / 4) * 3 - padding
        if (encoded.isEmpty() || encoded.length % 4 != 0 ||
            decodedSize <= 0 || decodedSize > 3 * 1024 * 1024
        ) throw TransportException("Project image exceeds the 3 MiB scoped limit")
    }
}

/**
 * PCB-LIVE-1 transport for PC-A's authenticated app surface (the /api/app
 * login + chat endpoints) through the currently configured JARVIS Gateway.
 *
 * Strategy B (runbook §5): this adapter converts PC-A's SSE chat protocol
 * (`event: ready|delta|complete|error`, JSON `data`) into the internal
 * [EventEnvelope] the existing pure reducer already consumes, so dedupe,
 * cancel-idempotency and streaming semantics are unchanged and no third
 * protocol exists. When PC-A exposes the frozen `/api/v1` Gateway, only this
 * class changes.
 *
 * Cancellation mirrors PC-A's own web client (auth.js): mark the turn, POST
 * the scoped cancel, abort the local stream, settle as Cancelled. A
 * disconnect-driven abort settles through `Reducer.onDisconnected` instead.
 */
class LiveAppGatewayTransport(
    private val session: JarvisAppSession,
    private val scope: CoroutineScope,
    private val attachmentStore: AttachmentStore? = null,
) : GatewayTransport {

    private companion object {
        const val MAX_INLINE_IMAGE_BYTES = 3_500_000
        const val MAX_INLINE_DOCUMENT_BYTES = 2_000_000
        const val MAX_INLINE_IMAGES_PER_TURN = 3
        const val AGENT_RECOVERY_BUDGET_MILLIS = 600_000L
        const val AGENT_RECOVERY_PROBE_TIMEOUT_MILLIS = 30_000L
        const val AGENT_RECOVERY_STEADY_WAIT_MILLIS = 15_000L
        val agentRecoveryBackoffMillis = listOf(2_000L, 4_000L, 8_000L)
    }

    private val _frames = Channel<String>(Channel.UNLIMITED)
    override val frames: Flow<String> = _frames.receiveAsFlow()

    private val _linkState = MutableStateFlow(LinkState.IDLE)
    override val linkState: StateFlow<LinkState> = _linkState.asStateFlow()

    private val json = Json { ignoreUnknownKeys = true }
    private val client = JarvisAppSession.defaultClient()
    private val agentStreamClient = client.newBuilder().readTimeout(45, TimeUnit.SECONDS).build()
    private val active = ConcurrentHashMap<String, ActiveTurn>()

    private val frameEmissionLock = Any()
    private var cursor = 0L
    private var eventSeq = 0L

    internal class TurnCtl {
        @Volatile var cancelRequested = false
        @Volatile var call: Call? = null
    }

    internal data class ActiveTurn(
        val clientRequestId: String,
        val conversationId: String,
        val traceId: String,
        val deviceId: String,
        val sessionId: String,
        val job: Job,
        val ctl: TurnCtl,
    )

    override suspend fun connect() {
        if (_linkState.value == LinkState.CONNECTED || _linkState.value == LinkState.CONNECTING) return
        val token = session.token
        if (token.isNullOrBlank() && !session.hasRefreshCredential) {
            _linkState.value = LinkState.FAILED
            throw TransportException("not authenticated")
        }
        _linkState.value = LinkState.CONNECTING
        val restored = session.restore()
        if (restored.isFailure) {
            _linkState.value = LinkState.FAILED
            emit(
                GatewayEvent.ConnectionState(
                    ConnectionPayload(ServerConnectionState.AUTH_EXPIRED, restored.exceptionOrNull()?.message),
                ),
            )
            throw TransportException("session invalid: ${restored.exceptionOrNull()?.message}")
        }
        _linkState.value = LinkState.CONNECTED
        emit(GatewayEvent.ConnectionState(ConnectionPayload(ServerConnectionState.ONLINE)))
    }

    override suspend fun disconnect() {
        active.values.forEach { it.job.cancel() }
        active.clear()
        _linkState.value = LinkState.CLOSED
    }

    override suspend fun send(request: MobileRequest) {
        if (_linkState.value != LinkState.CONNECTED) throw TransportException("live link not connected")
        when (request) {
            is MobileRequest.SendMessage -> handleSend(request)
            is MobileRequest.CancelRequest -> handleCancel(request)
            is MobileRequest.Replay -> Unit // no cursor journal on the app surface yet
            is MobileRequest.ResolveApproval ->
                throw TransportException("approvals not enabled on the live app surface yet (PA-5/6 gate)")
            is MobileRequest.UploadAttachment ->
                throw TransportException("attachment upload contract not frozen yet")
        }
    }

    override suspend fun health(): HealthResponse {
        val (code, _) = withContext(Dispatchers.IO) { session.get(session.baseUrl, "/api/status", auth = null) }
        if (code !in 200..299) throw TransportException("health $code")
        return HealthResponse(
            status = "ok",
            protocolVersion = "app-session-v1",
            capabilities = listOf("chat", "stream", "cancel", "recover"),
        )
    }

    override suspend fun deleteConversation(conversationId: String): Boolean = withContext(Dispatchers.IO) {
        val id = conversationId.trim()
        if (id.isEmpty() || id.length > 240) {
            throw TransportException("conversation id is invalid")
        }
        val auth = session.authHeader() ?: throw TransportException("no live session")
        val body = buildJsonObject { put("conversation_id", id) }.toString()
        val (status, responseBody) = session.post(
            session.baseUrl,
            "/api/app/chat/conversations/delete",
            body,
            auth,
        )
        if (status == 401) {
            session.clearAccess()
            throw TransportException("session expired", statusCode = status)
        }
        if (status !in 200..299) {
            throw TransportException("conversation deletion failed ($status)", statusCode = status)
        }
        val deleted = runCatching {
            json.parseToJsonElement(responseBody)
                .jsonObject["deleted"]
                ?.jsonPrimitive
                ?.content == "true"
        }.getOrNull()
        if (deleted != true) throw TransportException("conversation deletion response is invalid")
        true
    }

    // ---- send / stream --------------------------------------------------------

    private fun handleSend(req: MobileRequest.SendMessage) {
        val turnId = req.clientRequestId
        val traceId = UUID.randomUUID().toString()
        val deviceId = session.deviceId
        val sessionId = session.appSessionId
        val ctl = TurnCtl()

        val original = session.rememberTurn(
            turnId, req.conversationId, traceId, deviceId, sessionId,
        )
        val frozenProject = original.projectId
        val originalTraceId = original.traceId
        val originalDeviceId = original.deviceId
        val originalSessionId = original.sessionId
        // Register the request before the worker can emit a frame or complete.
        val job = scope.launch(Dispatchers.IO, start = CoroutineStart.LAZY) {
            try {
                emit(GatewayEvent.MessageAccepted(turnId, req.conversationId, "msg_$turnId"))
                streamChat(
                    req, originalTraceId, originalDeviceId, originalSessionId,
                    ctl, frozenProject,
                )
                emit(GatewayEvent.MessageCompleted(turnId, "msg_$turnId"))
                session.forgetTurn(turnId)
            } catch (t: CancellationException) {
                if (ctl.cancelRequested) {
                    emitQuietly(GatewayEvent.MessageCompleted(turnId, "msg_$turnId"))
                }
                // disconnect-driven cancel: Reducer.onDisconnected owns the state
                throw t
            } catch (t: Throwable) {
                when {
                    t is IOException && ctl.cancelRequested ->
                        emit(GatewayEvent.MessageCompleted(turnId, "msg_$turnId"))

                    // PC-A's own web client falls back to the JSON endpoint
                    // when the SSE route is absent (404/405 before any frame).
                    t is StreamUnavailable -> {
                        val completed = runCatching {
                            postJsonTurn(req, originalTraceId, originalDeviceId, originalSessionId)
                        }.getOrNull()
                        if (completed != null) {
                            emitCompletedWithMedia(completed, turnId, req.conversationId)
                            session.forgetTurn(turnId)
                        } else {
                            emit(
                                GatewayEvent.MessageFailed(
                                    turnId, "msg_$turnId",
                                    ErrorEnvelope("live_error", "stream unavailable"),
                                    retryable = false,
                                ),
                            )
                        }
                    }

                    // Stream broke mid-turn: PC-A may already hold the finished
                    // turn; reconcile through GET /requests/{id} rather than
                    // paying for a second inference (matches auth.js recovery).
                    // The request is already Accepted/Streaming locally, so
                    // settle it with the cached text only — no second accepted.
                    t is StreamInterrupted || (t is IOException && !ctl.cancelRequested) -> {
                        val cached = try {
                            awaitCachedTurn(turnId)
                        } catch (cancelled: CancellationException) {
                            throw cancelled
                        } catch (failure: Exception) {
                            null
                        }
                        if (cached != null) {
                            emitCompletedWithMedia(cached, turnId, req.conversationId)
                            session.forgetTurn(turnId)
                        } else {
                            emit(
                                GatewayEvent.MessageFailed(
                                    turnId, "msg_$turnId",
                                    ErrorEnvelope("stream_interrupted", t.message ?: "stream ended early"),
                                    retryable = false,
                                ),
                            )
                        }
                    }

                    else -> emit(
                        GatewayEvent.MessageFailed(
                            turnId,
                            "msg_$turnId",
                            ErrorEnvelope("live_error", t.message ?: "stream failed"),
                            retryable = false,
                        ),
                    )
                }
            } finally {
                active.remove(turnId)
            }
        }
        val registered = ActiveTurn(
            turnId, req.conversationId, originalTraceId, originalDeviceId,
            originalSessionId, job, ctl,
        )
        if (active.putIfAbsent(turnId, registered) != null) {
            job.cancel()
            throw TransportException("Request is already active")
        }
        if (!job.start()) {
            active.remove(turnId, registered)
            throw TransportException("Chat transport is unavailable")
        }
    }

    /** SSE route missing on this PC-A build; caller falls back to JSON chat. */
    private class StreamUnavailable : Exception("sse_unavailable")

    /** Stream opened but closed without a terminal frame; try turn recovery. */
    private class StreamInterrupted : Exception("stream_interrupted")

    private suspend fun streamChat(
        req: MobileRequest.SendMessage,
        traceId: String,
        deviceId: String,
        sessionId: String,
        ctl: TurnCtl,
        projectAgent: String?,
    ) {
        // Freeze the chosen project when the turn is persisted, not when the
        // asynchronous HTTP coroutine eventually starts. A selection change
        // must never reroute an already-accepted private message.
        if (projectAgent != null) {
            emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                taskId = "chat_${req.clientRequestId}",
                requestId = req.clientRequestId,
                status = TaskStatus.RUNNING,
                label = "Consultando herramientas del proyecto",
            )))
            // Serialize attachments with the SAME bounded inline-media
            // contract as regular Chat Global. Never discard project_id.
            val projectMedia = if (req.attachmentIds.isNotEmpty()) {
                json.parseToJsonElement(
                    chatPayload(req, traceId, deviceId, sessionId)).jsonObject
            } else null
            val images = projectMedia?.get("images")?.jsonArray
            val documents = projectMedia?.get("documents")?.jsonArray
            requireProjectAgentMediaWithinWireContract(images, documents)
            val reply = session.chatGlobalProjectAgentTurn(
                projectId = projectAgent,
                conversationId = req.conversationId,
                requestId = req.clientRequestId,
                prompt = req.text,
                images = images,
                documents = documents,
                frozenTraceId = traceId,
                frozenDeviceId = deviceId,
                frozenSessionId = sessionId,
            ).getOrThrow()
            val echoed = reply.request
            if (reply.schema != "jarvis.chat.turn.v1" ||
                reply.route != "adaptive_agent" ||
                echoed == null ||
                echoed.request_id != req.clientRequestId ||
                echoed.conversation_id != req.conversationId ||
                echoed.trace_id != traceId ||
                echoed.device_id != deviceId ||
                echoed.session_id != sessionId
            ) {
                throw TransportException("Project reply scope mismatch")
            }
            if (ctl.cancelRequested || !currentCoroutineContext().isActive) {
                throw CancellationException("Project agent turn cancelled")
            }
            val text = reply.response.text
            if (text.isBlank()) throw TransportException("Agent returned no answer")
            // Reuse exactly the same validated receipt codec as general chat.
            // Cite only the signed web:hash refs in this project-bound turn;
            // never derive a source from arbitrary agent/model text.
            val sourcesJson = com.jarvis.android.data.repo.ChatSourcesCodec
                .encodeValidated(reply.content)
            if (sourcesJson.isNotBlank() && sourcesJson != "[]") {
                session.onAgentSourcesReady?.invoke(
                    req.conversationId, req.clientRequestId, sourcesJson,
                )
            }
            emit(GatewayEvent.MessageDelta(
                req.clientRequestId, "msg_${req.clientRequestId}", 0, text,
            ))
            emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                taskId = "chat_${req.clientRequestId}",
                requestId = req.clientRequestId,
                status = TaskStatus.COMPLETED,
            )))
            emit(GatewayEvent.MessageCompleted(
                requestId = req.clientRequestId,
                messageId = "msg_${req.clientRequestId}",
                fullText = text,
                provider = reply.response.provider.ifBlank { null },
                model = reply.response.model.ifBlank { null },
                route = reply.route.ifBlank { null },
                destination = "adaptive_agent",
            ))
            return
        }

        val payload = chatPayload(req, traceId, deviceId, sessionId)
        // The adaptive general agent now accepts bounded inline images and
        // one document. Existing backend parses them with the same JARVIS
        // validators; older deployments continue on legacy streaming.
        val generalAgent = session.generalChatAgentEnabled && projectAgent == null
        val endpoint = if (generalAgent) "/api/app/chat/agent/general/stream"
                       else "/api/app/chat/stream"

        val request = Request.Builder()
            .url(session.baseUrl + endpoint)
            .header("Accept", "text/event-stream")
            .header("Authorization", session.authHeader() ?: throw TransportException("no token"))
            .post(payload.toRequestBody(JarvisAppSession.JSON_MEDIA))
            .build()

        var seq = 0
        var completed = false
        val call = (if (generalAgent) agentStreamClient else client).newCall(request)
        ctl.call = call
        call.execute().use { resp ->
            if (resp.code == 401) {
                emit(
                    GatewayEvent.ConnectionState(
                        ConnectionPayload(ServerConnectionState.AUTH_EXPIRED, "token expired"),
                    ),
                )
                throw TransportException("auth expired")
            }
            if (resp.code == 404 || resp.code == 405) throw StreamUnavailable()
            if (resp.code !in 200..299) {
                val body = resp.body?.string()?.take(2_000).orEmpty()
                throw TransportException(ChatErrorText.fromHttp(resp.code, body))
            }
            val reader = resp.body?.charStream()?.buffered() ?: throw TransportException("empty stream body")
            var eventName = ""
            val dataLines = StringBuilder()
            while (currentCoroutineContext().isActive) {
                val line = reader.readLine() ?: break
                when {
                    line.isEmpty() -> {
                        if (eventName.isNotEmpty() || dataLines.isNotEmpty()) {
                            completed = handleSFrame(eventName, dataLines.toString(), req.clientRequestId, seq,
                                req.conversationId)
                                .let { completed || it }
                            if (eventName == "delta") seq++
                            eventName = ""
                            dataLines.setLength(0)
                        }
                    }
                    line.startsWith("event:") -> eventName = line.removePrefix("event:").trim()
                    line.startsWith("data:") -> {
                        if (dataLines.isNotEmpty()) dataLines.append('\n')
                        dataLines.append(line.removePrefix("data:").trimStart())
                    }
                }
            }
        }
        if (!completed && !ctl.cancelRequested) {
            throw StreamInterrupted()
        }
    }

    private data class CompletedTurn(
        val text: String,
        val sourcesJson: String = "",
        val provider: String = "",
        val model: String = "",
        val route: String = "",
        val destination: String = "",
        val generatedImages: List<GlobalImageReceipt> = emptyList(),
    ) {
        fun toEvent(requestId: String) = GatewayEvent.MessageCompleted(
            requestId = requestId,
            messageId = "msg_$requestId",
            fullText = text,
            provider = provider.ifBlank { null },
            model = model.ifBlank { null },
            route = route.ifBlank { null },
            destination = destination.ifBlank { null },
        )
    }

    private fun parseCompletedTurn(body: String): CompletedTurn? = runCatching {
        val obj = json.parseToJsonElement(body).jsonObject
        val response = obj["response"]?.jsonObject ?: return@runCatching null
        val request = obj["request"]?.jsonObject
        val text = response["text"]?.jsonPrimitive?.content.orEmpty()
        val assets = parseGlobalImageReceipts(obj)
        if (text.isBlank() && assets.isEmpty()) return@runCatching null
        CompletedTurn(
            text = text,
            provider = response["provider"]?.jsonPrimitive?.content
                ?: request?.get("resolved_provider")?.jsonPrimitive?.content.orEmpty(),
            model = response["model"]?.jsonPrimitive?.content
                ?: request?.get("resolved_model")?.jsonPrimitive?.content.orEmpty(),
            route = obj["route"]?.jsonPrimitive?.content.orEmpty(),
            destination = request?.get("resolved_destination")?.jsonPrimitive?.content.orEmpty(),
            generatedImages = assets,
            sourcesJson = com.jarvis.android.data.repo.ChatSourcesCodec.encodeValidated(
                obj["content"]?.let { runCatching { it.jsonObject }.getOrNull() }),
        )
    }.getOrNull()

    /** A cached turn must restore the exact same media as its SSE completion.
     * The request-scoped asset ID is only a download reference, never a new
     * generation. Repeated delivery is keyed by requestId in the ViewModel.
     */
    private suspend fun emitCompletedWithMedia(
        completed: CompletedTurn, requestId: String, conversationId: String,
    ) {
        if (completed.sourcesJson.isNotBlank() && completed.sourcesJson != "[]") {
            session.onAgentSourcesReady?.invoke(
                conversationId, requestId, completed.sourcesJson)
        }
        completed.generatedImages.forEach { receipt ->
            try {
                val raw = session.downloadAgentImage(receipt.assetId)
                if (!verifiedGlobalImageBytes(receipt, raw)) {
                    throw TransportException("Generated image receipt hash or MIME mismatch")
                }
                // Keep original PNG/JPEG/WebP bytes for exact later editing.
                // Thumbnail decoding is independent of the immutable source.
                val staged = attachmentStore?.stageVerifiedGeneratedBase64(
                    Base64.getEncoder().encodeToString(raw),
                    expectedSha256 = receipt.sha256,
                    expectedMimeType = receipt.mimeType,
                    stableReceiptKey = "$conversationId:$requestId:${receipt.assetId}",
                ) ?: throw TransportException("Verified image storage unavailable")
                session.onAgentImageReady?.invoke(
                    conversationId, requestId, staged.attachmentId)
            } catch (failure: Exception) {
                session.onAgentImageError?.invoke(
                    failure.message ?: "Generated image could not be retrieved")
            }
        }
        emit(completed.toEvent(requestId))
    }

    /** Bounded JSON smoke path when the SSE route is absent on this PC-A build. */
    private suspend fun postJsonTurn(
        req: MobileRequest.SendMessage,
        traceId: String,
        deviceId: String,
        sessionId: String,
    ): CompletedTurn? {
        val payload = chatPayload(req, traceId, deviceId, sessionId)
        val (code, body) = withContext(Dispatchers.IO) {
            session.post(
                session.baseUrl, "/api/app/chat", payload,
                session.authHeader() ?: throw TransportException("no token"),
            )
        }
        if (code !in 200..299) return null
        return parseCompletedTurn(body)
    }

    private fun chatPayload(
        req: MobileRequest.SendMessage,
        traceId: String,
        deviceId: String,
        sessionId: String,
    ): String {
        val inlineImages = mutableListOf<Pair<String, String>>()
        val inlineDocuments = mutableListOf<Triple<String, String, String>>()
        req.attachmentIds.forEach { attachmentId ->
            val store = attachmentStore
                ?: throw TransportException("attachments are unavailable on this transport")
            val file = store.resolve(attachmentId)
                ?: throw TransportException("attachment is missing from private storage")
            val bytes = file.readBytes()
            val extension = file.extension.lowercase()
            if (extension in setOf("jpg", "jpeg", "png", "webp")) {
                if (bytes.isEmpty() || bytes.size > MAX_INLINE_IMAGE_BYTES) {
                    throw TransportException("image attachment is too large for this JARVIS version")
                }
                val mime = when (extension) {
                    "png" -> "image/png"
                    "webp" -> "image/webp"
                    else -> "image/jpeg"
                }
                inlineImages += mime to Base64.getEncoder().encodeToString(bytes)
            } else {
                if (bytes.isEmpty() || bytes.size > MAX_INLINE_DOCUMENT_BYTES) {
                    throw TransportException("document is too large for this JARVIS version")
                }
                val mime = when (extension) {
                    "txt" -> "text/plain"
                    "md" -> "text/markdown"
                    "pdf" -> "application/pdf"
                    "docx" -> "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
                    else -> throw TransportException("unsupported document type")
                }
                inlineDocuments += Triple(
                    mime,
                    store.documentFilename(attachmentId) ?: "document.$extension",
                    Base64.getEncoder().encodeToString(bytes),
                )
            }
        }
        if (inlineImages.size > MAX_INLINE_IMAGES_PER_TURN) {
            throw TransportException("JARVIS supports up to three images per turn")
        }
        if (inlineDocuments.size > 1 || (inlineDocuments.isNotEmpty() && inlineImages.isNotEmpty())) {
            throw TransportException("Attach one document or up to three images per turn")
        }

        return buildJsonObject {
            put("mode", "auto")
            put("profile", session.chatProfileFor(req.conversationId))
            // Never send forced effort unless the user selected one. Legacy
            // deployments continue to use the provider's native defaults.
            session.chatEffortFor(req.conversationId).takeIf { it != "auto" }?.let {
                put("effort", it)
            }
            put("session_id", sessionId)
            put("conversation_id", req.conversationId)
            put("device_id", deviceId)
            put("request_id", req.clientRequestId)
            put("trace_id", traceId)
            put("messages", buildJsonArray {
                req.context.forEach { turn ->
                    addJsonObject {
                        put("role", turn.role)
                        put("content", turn.content)
                    }
                }
                addJsonObject {
                    put("role", "user")
                    put("content", req.text)
                }
            })
            if (inlineImages.isNotEmpty()) {
                put("images", buildJsonArray {
                    inlineImages.forEach { (mime, imageBase64) ->
                        addJsonObject {
                            put("mime_type", mime)
                            put("data_base64", imageBase64)
                        }
                    }
                })
            }
            if (inlineDocuments.isNotEmpty()) {
                put("documents", buildJsonArray {
                    inlineDocuments.forEach { (mime, filename, base64) ->
                        addJsonObject {
                            put("mime_type", mime)
                            put("filename", filename)
                            put("data_base64", base64)
                        }
                    }
                })
            }
        }.toString()
    }

    /** Returns true when this frame is the terminal `complete`. */
    private suspend fun handleSFrame(
        event: String, data: String, requestId: String, seq: Int, conversationId: String,
    ): Boolean {
        if (data.isBlank()) return false
        when (event) {
            "ready" -> Unit // accepted already emitted when the turn started
            "progress" -> {
                val phase = runCatching {
                    json.parseToJsonElement(data).jsonObject["phase"]?.jsonPrimitive?.content
                }.getOrNull()
                val label = when (phase) {
                    "searching_web" -> "Searching the web"
                    "reviewing_sources" -> "Reviewing sources"
                    "analyzing_image" -> "Analyzing image"
                    "reading_document" -> "Reading document"
                    "generating_answer" -> "Writing answer"
                    else -> null
                }
                if (label != null) {
                    emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                        taskId = "chat_$requestId",
                        requestId = requestId,
                        status = TaskStatus.RUNNING,
                        label = label,
                    )))
                }
            }
            "delta" -> {
                val text = runCatching {
                    json.parseToJsonElement(data).jsonObject["delta"]?.jsonPrimitive?.content
                }.getOrNull().orEmpty()
                if (text.isNotEmpty()) {
                    emit(GatewayEvent.MessageDelta(requestId, "msg_$requestId", seq, text))
                }
            }
            "complete" -> {
                emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                    taskId = "chat_$requestId", requestId = requestId,
                    status = TaskStatus.COMPLETED,
                )))
                val completed = parseCompletedTurn(data)
                if (completed != null) {
                    emitCompletedWithMedia(completed, requestId, conversationId)
                } else {
                    emit(GatewayEvent.MessageCompleted(requestId, "msg_$requestId"))
                }
                return true
            }
            "error" -> {
                val code = runCatching {
                    json.parseToJsonElement(data).jsonObject["error"]?.jsonPrimitive?.content
                }.getOrNull()
                val retrySafe = runCatching {
                    json.parseToJsonElement(data).jsonObject["retry_safe"]?.jsonPrimitive
                        ?.takeIf { !it.isString }?.booleanOrNull
                }.getOrNull() == true
                if (code == "chat_cancelled") {
                    emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                        taskId = "chat_$requestId", requestId = requestId,
                        status = TaskStatus.CANCELLED,
                    )))
                    emit(GatewayEvent.MessageCompleted(requestId, "msg_$requestId"))
                } else {
                    // The backend may already hold a finished paid turn: settle it before offering any retry.
                    val cached = try {
                        fetchCachedTurn(requestId)
                    } catch (cancelled: CancellationException) {
                        throw cancelled
                    } catch (failure: Exception) {
                        null
                    }
                    if (cached != null) {
                        emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                            taskId = "chat_$requestId", requestId = requestId,
                            status = TaskStatus.COMPLETED,
                        )))
                        emitCompletedWithMedia(cached, requestId, conversationId)
                        session.forgetTurn(requestId)
                        return true
                    }
                    emit(GatewayEvent.TaskUpdated(TaskUpdatedPayload(
                        taskId = "chat_$requestId", requestId = requestId,
                        status = TaskStatus.FAILED,
                    )))
                    emit(
                        GatewayEvent.MessageFailed(
                            requestId,
                            "msg_$requestId",
                            ErrorEnvelope(code ?: "stream_error", "assistant stream error"),
                            retryable = retrySafe && code !in setOf(
                                "chat_timeout", "general_agent_incomplete",
                                "agent_outcome_unknown", "outcome_unknown",
                                "image_result_unknown", "paid_operation_uncertain",
                            ),
                        ),
                    )
                }
                return true
            }
        }
        return false
    }

    // ---- cancel ---------------------------------------------------------------

    private fun handleCancel(req: MobileRequest.CancelRequest) {
        val turn = active.values.firstOrNull { it.clientRequestId == req.targetRequestId } ?: return
        turn.ctl.cancelRequested = true
        scope.launch(Dispatchers.IO) {
            val body = buildJsonObject {
                put("user_id", session.userId)
                put("device_id", turn.deviceId)
                put("session_id", turn.sessionId)
                put("conversation_id", turn.conversationId)
                put("request_id", turn.clientRequestId)
                put("trace_id", turn.traceId)
            }.toString()
            runCatching {
                session.post(session.baseUrl, "/api/app/chat/cancel", body, session.authHeader())
            }
            turn.ctl.call?.cancel()
            turn.job.cancel()
        }
    }

    /**
     * GET /api/app/chat/requests/{id} with X-Jarvis-* scope. Returns the cached
     * assistant text when PC-A already completed the turn, else null. Never
     * triggers a second inference.
     */
    private suspend fun fetchCachedTurn(clientRequestId: String): CompletedTurn? =
        (readCachedTurn(clientRequestId) as? CachedTurn.Completed)?.turn

    private sealed interface CachedTurn {
        data class Completed(val turn: CompletedTurn) : CachedTurn
        data object InFlight : CachedTurn
        data object Unavailable : CachedTurn
    }

    /**
     * Stream-interrupted recovery: a turn PC-A still runs is re-read read-only
     * on a bounded backoff. The pending row is kept until a terminal answer.
     */
    private suspend fun awaitCachedTurn(clientRequestId: String): CompletedTurn? {
        val deadlineNanos = System.nanoTime() + AGENT_RECOVERY_BUDGET_MILLIS * 1_000_000L
        var attempt = 0
        while (true) {
            val observed = try {
                readCachedTurn(clientRequestId, AGENT_RECOVERY_PROBE_TIMEOUT_MILLIS)
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (network: IOException) {
                // A cut connection says nothing about the turn the server is still running.
                CachedTurn.InFlight
            }
            when (val state = observed) {
                is CachedTurn.Completed -> return state.turn
                CachedTurn.InFlight -> Unit
                CachedTurn.Unavailable -> return null
            }
            val remainingMillis = (deadlineNanos - System.nanoTime()) / 1_000_000L
            if (remainingMillis <= 0L) return null
            val wait = agentRecoveryBackoffMillis.getOrElse(attempt) { AGENT_RECOVERY_STEADY_WAIT_MILLIS }
            delay(minOf(wait, remainingMillis))
            attempt++
        }
    }

    private suspend fun readCachedTurn(clientRequestId: String, callTimeoutMillis: Long? = null): CachedTurn {
        val stored = session.loadTurn(clientRequestId) ?: return CachedTurn.Unavailable
        val request = Request.Builder()
            .url(
                session.baseUrl + "/api/app/chat/requests/" +
                    java.net.URLEncoder.encode(clientRequestId, "UTF-8"),
            )
            .get()
            .apply {
                session.authHeader()?.let { header("Authorization", it) }
                header("X-Jarvis-User-Id", session.userId)
                header("X-Jarvis-Device-Id", stored.deviceId)
                header("X-Jarvis-Session-Id", stored.sessionId)
                header("X-Jarvis-Conversation-Id", stored.conversationId)
                header("X-Jarvis-Trace-Id", stored.traceId)
            }
            .build()
        return withContext(Dispatchers.IO) {
            val call = client.newCall(request)
            callTimeoutMillis?.let { call.timeout().timeout(it, TimeUnit.MILLISECONDS) }
            call.execute().use { resp ->
                if (resp.code in 500..599) return@use CachedTurn.InFlight
                if (resp.code !in 200..299) return@use CachedTurn.Unavailable
                val body = resp.body?.string() ?: return@use CachedTurn.Unavailable
                runCatching {
                    val obj = json.parseToJsonElement(body).jsonObject
                    if (obj["schema"]?.jsonPrimitive?.content != "jarvis.chat.turn.v1") {
                        return@use CachedTurn.Unavailable
                    }
                    // The recovery GET is authenticated and scoped, but a stale
                    // proxy/cache or backend regression must not cross-wire a
                    // turn that *does* echo its immutable request identity.
                    // Legacy replies without an echo remain supported.
                    val echoed = obj["request"]
                    if (echoed != null) {
                        val fields = runCatching { echoed.jsonObject }.getOrNull()
                            ?: return@use CachedTurn.Unavailable
                        val identity = listOf(
                            "request_id" to clientRequestId,
                            "conversation_id" to stored.conversationId,
                            "trace_id" to stored.traceId,
                            "device_id" to stored.deviceId,
                            "session_id" to stored.sessionId,
                        )
                        if (identity.any { (key, original) ->
                                val actual = fields[key] ?: return@any false
                                runCatching { actual.jsonPrimitive.content }.getOrNull() != original
                            }) {
                            return@use CachedTurn.Unavailable
                        }
                    }
                    when (obj["result"]?.jsonObject?.get("status")?.jsonPrimitive?.content) {
                        "completed" -> parseCompletedTurn(body)?.let { CachedTurn.Completed(it) } ?: CachedTurn.Unavailable
                        "active", "queued", "running" -> CachedTurn.InFlight
                        else -> CachedTurn.Unavailable
                    }
                }.getOrDefault(CachedTurn.Unavailable)
            }
        }
    }

    /**
     * Process-death recovery: the fresh session has no knowledge of this
     * request, so emit accepted+completed from the cached server turn.
     */
    override suspend fun recoverCompletedTurn(clientRequestId: String, conversationId: String): Boolean {
        val frozen = session.loadTurn(clientRequestId) ?: return false
        if (frozen.conversationId != conversationId ||
            frozen.principalId != null && frozen.principalId != session.userId
        ) return false
        val completed = fetchCachedTurn(clientRequestId) ?: return false
        emit(GatewayEvent.MessageAccepted(clientRequestId, conversationId, "msg_$clientRequestId"))
        emitCompletedWithMedia(completed, clientRequestId, conversationId)
        session.forgetTurn(clientRequestId)
        return true
    }

    // ---- frame production (internal EventEnvelope for the existing reducer) ---

    private suspend fun emit(event: GatewayEvent) = emitFrame(event)

    /** Non-suspending variant usable from a cancelled coroutine. */
    private fun emitQuietly(event: GatewayEvent) = emitFrame(event)

    // Allocate IDs and enqueue in the same critical section. Parallel streams
    // must never reuse an event ID or deliver a lower cursor after a higher one.
    internal fun emitFrame(event: GatewayEvent) {
        synchronized(frameEmissionLock) {
            val env = EventEnvelope(
                cursor = ++cursor,
                eventId = "live_${eventSeq++}",
                version = ContractVersion.SUPPORTED,
                timestampMs = System.currentTimeMillis(),
                event = event,
            )
            _frames.trySend(JarvisJson.default.encodeToString(EventEnvelope.serializer(), env))
        }
    }
