fun findCharacter(id: String): StoryCharacter? =
    CANON_CHARACTERS.firstOrNull { it.id.equals(id, ignoreCase = true) }

fun searchCharacters(query: String): List<StoryCharacter> {
    val clean = query.trim().lowercase()
    if (clean.isEmpty()) return CANON_CHARACTERS
    return CANON_CHARACTERS.filter { c ->
        c.name.lowercase().contains(clean) ||
            c.epithet.lowercase().contains(clean) ||
            c.faction.lowercase().contains(clean) ||
            c.role.lowercase().contains(clean) ||
            c.powersOverview.lowercase().contains(clean) ||
            c.storyHistory.lowercase().contains(clean) ||
            c.signatureTechniques.any { it.first.lowercase().contains(clean) || it.second.lowercase().contains(clean) }
    }
}

